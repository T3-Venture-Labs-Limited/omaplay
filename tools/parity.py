#!/usr/bin/env python3
"""Generate docs/PARITY.md and docs/parity/inventory.tsv.

Parity method (mechanical, so it can be re-run after every upstream update):
  1. Inventory every entry point from the pinned VLC source: command-line options and hotkeys (from a
     --full-help run of the stock baseline and of this build), menu labels, control-bar controls,
     dialog slots, and every QML file of the interface.
  2. For each entry, say whether the source file that defines it is byte-identical to stock at the
     pinned commit. Identical files cannot have lost behaviour. Files we changed are listed with the
     commit that changed them, and need a manual check (docs/parity/manual.md).
  3. Compare the option set of this build against the stock baseline.
"""
import re, subprocess, sys, os, collections, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
vlc = root / "vlc"
sha = next(l.split()[0] for l in open(root / "UPSTREAM") if not l.startswith("#"))

def git(*a):
    return subprocess.run(["git", "-C", str(vlc), *a], capture_output=True, text=True, check=True).stdout

changed = set(git("diff", "--name-only", f"{sha}..HEAD").split())
why = {}
for f in changed:
    subjects = git("log", "--format=%s", f"{sha}..HEAD", "--", f).strip().splitlines()
    why[f] = subjects[-1] if subjects else "?"   # the commit that first touched it

def easing_only(f):
    """True when every changed line of f is an easing curve (the mechanical ease-out replacement)."""
    lines = [l[1:].strip() for l in git("diff", "-U0", f"{sha}..HEAD", "--", f).splitlines()
             if l[:1] in "+-" and not l.startswith(("+++", "---"))]
    return bool(lines) and all("easing.type" in l for l in lines)

kind = {f: ("easing curves only" if f.endswith(".qml") and easing_only(f) else "behaviour-relevant edit") for f in changed}

qt = "modules/gui/qt"
rows = []   # (category, entry, file, status)

def status(f):
    return "changed" if f in changed else "identical"

# ---- menu labels
src = (vlc / qt / "menus/menus.cpp").read_text()
for label in sorted(set(re.findall(r'qtr\(\s*"([^"]+)"', src))):
    rows.append(("menu", label, f"{qt}/menus/menus.cpp", status(f"{qt}/menus/menus.cpp")))

# ---- control-bar controls
for p in sorted((vlc / qt / "player/qml/controlbarcontrols").glob("*.qml")):
    rel = str(p.relative_to(vlc))
    rows.append(("control", p.stem, rel, status(rel)))

# ---- dialog slots
src = (vlc / qt / "dialogs/dialogs_provider.hpp").read_text()
slots = src[src.index("public slots:"):]
for name in sorted(set(re.findall(r"\bvoid\s+(\w*[Dd]ialog\w*)\s*\(", slots))):
    rows.append(("dialog", name, f"{qt}/dialogs/dialogs_provider.hpp", status(f"{qt}/dialogs/dialogs_provider.hpp")))

# ---- QML files
for p in sorted((vlc / qt).rglob("*.qml")):
    rel = str(p.relative_to(vlc))
    if "/tests/" in rel:
        continue
    rows.append(("qml", rel[len(qt) + 1:], rel, status(rel)))

# ---- command-line options and hotkeys, from the stock baseline and this build's --full-help
def options(text):
    return set(re.findall(r"^\s+(?:-\w, )?(--[a-z0-9][a-z0-9-]*)", text, re.M))

baseline = options((root / "docs/baseline/vlc4-full-help.txt").read_text())
build = root / "build"
env = dict(os.environ, VLC_LIB_PATH=f"{build}/modules", VLC_PLUGIN_PATH=f"{build}/modules",
           XDG_CONFIG_HOME="/tmp/omaplay-parity/c", XDG_DATA_HOME="/tmp/omaplay-parity/d", XDG_CACHE_HOME="/tmp/omaplay-parity/k")
help_run = subprocess.run([str(build / "bin/vlc-static"), "--full-help", "--advanced"], capture_output=True, text=True, env=env)
ours = options(help_run.stdout + help_run.stderr)
missing = sorted(baseline - ours)
added = sorted(ours - baseline)
for o in sorted(baseline):
    rows.append(("option", o, "src/libvlc-module.c + modules", "present" if o in ours else "MISSING"))
    if o.startswith("--key-"):
        rows[-1] = ("hotkey", o, "src/libvlc-module.c", "present" if o in ours else "MISSING")

# ---- write
(root / "docs/parity").mkdir(exist_ok=True)
with open(root / "docs/parity/inventory.tsv", "w") as fh:
    fh.write("category\tentry\tfile\tstatus\n")
    for r in rows:
        fh.write("\t".join(r) + "\n")

by = collections.defaultdict(collections.Counter)
for c, e, f, s in rows:
    by[c][s] += 1

manual = root / "docs/parity/manual.md"
out = ["# Parity checklist", "",
       f"Generated by `tools/parity.py` against upstream `{sha[:12]}`; do not edit by hand (edit `docs/parity/manual.md`).",
       "", "Rule: every stock VLC 4 entry point must still exist. An entry whose defining file is **identical** to stock cannot have lost",
       "behaviour. An entry in a **changed** file is listed below with the commit that changed it and needs a manual check.", "",
       "## Summary", "", "| Category | Entries | Identical to stock | In a changed file | Missing |", "|---|---:|---:|---:|---:|"]
for c in ("hotkey", "option", "menu", "control", "dialog", "qml"):
    cnt = by[c]; total = sum(cnt.values())
    ident = cnt["identical"] + cnt["present"]
    out.append(f"| {c} | {total} | {ident} | {cnt['changed']} | {cnt['MISSING']} |")
out += ["", f"Command-line options and hotkeys: **{len(baseline)}** in the stock baseline, **{len(ours)}** in this build;",
        f"missing from this build: **{len(missing)}**" + (" (" + ", ".join(missing) + ")" if missing else "") + ";",
        f"added by this build: **{len(added)}**" + (" (" + ", ".join(added) + ")" if added else "") + ".", ""]
chg_rows = [(c, e, f) for c, e, f, s in rows if s == "changed"]
files = collections.OrderedDict()
for c, e, f in chg_rows:
    files.setdefault(f, []).append(f"{c}:{e}")
n_easing = sum(1 for f in files if kind.get(f) == "easing curves only")
out += ["## Entry points in files this fork changed", "",
        f"{len(files)} files; **{n_easing}** differ from stock only in easing curves (animation shape, no behaviour).", "",
        "| File | Kind of change | Entries | Changed by |", "|---|---|---|---|"]
for f, ents in files.items():
    shown = ", ".join(ents[:4]) + (f" (+{len(ents) - 4} more)" if len(ents) > 4 else "")
    out.append(f"| `{f}` | {kind.get(f, '?')} | {shown} | {why.get(f, '?')} |")
out.append("")
if manual.exists():
    out += ["## Manual verification", "", manual.read_text()]
(root / "docs/PARITY.md").write_text("\n".join(out) + "\n")
print(f"{len(rows)} entries; {len(chg_rows)} in changed files; {len(missing)} options missing; {len(added)} added")
sys.exit(1 if missing else 0)
